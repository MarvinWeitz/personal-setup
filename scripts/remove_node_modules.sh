#!/usr/bin/env bash

# Usage: ./remove_node_modules.sh /path/to/base [--dry-run]

BASE_DIR="$1"
DRY_RUN=false

# Check if base directory is given
if [ -z "$BASE_DIR" ]; then
    echo "Usage: $0 /path/to/base [--dry-run]"
    exit 1
fi

# Check if --dry-run is specified
if [ "$2" == "--dry-run" ]; then
    DRY_RUN=true
fi

# Validate base directory
if [ ! -d "$BASE_DIR" ]; then
    echo "Error: '$BASE_DIR' is not a valid directory."
    exit 1
fi

echo "Searching for 'node_modules' directories under: $BASE_DIR"
echo

# Find only the node_modules directories (no subfolders listed)
FOUND_DIRS=$(find "$BASE_DIR" -type d -name "node_modules" -prune 2>/dev/null)

if [ -z "$FOUND_DIRS" ]; then
    echo "No 'node_modules' directories found."
    exit 0
fi

if $DRY_RUN; then
    echo "[Dry Run] The following directories would be deleted:"
    echo "$FOUND_DIRS" | while IFS= read -r dir; do
        echo "$dir"
    done
else
    echo "Deleting the following directories:"
    echo "$FOUND_DIRS" | while IFS= read -r dir; do
        echo "$dir"
        rm -rf "$dir"
    done
    echo "Deletion complete."
fi
